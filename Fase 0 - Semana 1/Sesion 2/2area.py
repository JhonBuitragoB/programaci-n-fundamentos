# Área de un rectangulo

# Variables del programa
linea = "=" * 10
print(f"{linea} PROGRAMA PARA CALCULAR EL ÁREA DE UN RECTANGULO {linea}\n")
base = float(input("Ingrese el base: "))
altura = float(input("Ingrese la altura: "))
area = base * altura

# Salidas
print(f"\n{linea} Proceso del programa {linea}\n")
print(f"La base es: {base:.2f}\n"
    f"La altura es: {altura:.2f}\n"
    f"El área del rectangulo es: {area:.2f}"
    )
print(f"\n{linea} Fin del programa {linea}\n")

